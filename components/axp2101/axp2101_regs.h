#pragma once

#include <stdint.h>

#define AXP2101_I2C_ADDR_7BIT 0x34

#define AXP2101_REG_STATUS0 0x00
#define AXP2101_REG_STATUS1 0x01
#define AXP2101_REG_STATUS2 AXP2101_REG_STATUS1

#define AXP2101_REG_ADC_CHANNEL_CTRL 0x30
#define AXP2101_ADC_CHANNEL_BATTERY (1u << 0)
#define AXP2101_ADC_CHANNEL_VBUS (1u << 2)
#define AXP2101_ADC_CHANNEL_VSYS (1u << 3)
#define AXP2101_ADC_CHANNEL_VOLTAGE_MASK                                   \
    (AXP2101_ADC_CHANNEL_BATTERY | AXP2101_ADC_CHANNEL_VBUS |              \
     AXP2101_ADC_CHANNEL_VSYS)

#define AXP2101_REG_BATTERY_H 0x34
#define AXP2101_REG_BATTERY_L 0x35
#define AXP2101_REG_VBUS_H 0x38
#define AXP2101_REG_VBUS_L 0x39
#define AXP2101_REG_VSYS_H 0x3A
#define AXP2101_REG_VSYS_L 0x3B

#define AXP2101_REG_IRQ0 0x48
#define AXP2101_REG_IRQ1 0x49
#define AXP2101_REG_IRQ2 0x4A

#define AXP2101_REG_BAT_PERCENT 0xA4

#define AXP2101_STATUS0_VBUS_GOOD (1u << 5)
#define AXP2101_STATUS0_BATTERY_PRESENT (1u << 3)
#define AXP2101_STATUS0_BATFET_ON (1u << 4)

#define AXP2101_STATUS2_BAT_DIR_SHIFT 5
#define AXP2101_STATUS2_BAT_DIR_MASK 0x07u
#define AXP2101_STATUS2_BAT_DIR_STANDBY 0x00u
#define AXP2101_STATUS2_BAT_DIR_CHARGE 0x01u
#define AXP2101_STATUS2_BAT_DIR_DISCHARGE 0x02u

#define AXP2101_ADC_14BIT_MASK 0x3FFFu
